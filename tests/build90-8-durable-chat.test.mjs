  assert.match(sql,/unique\(user_id,request_id\)/);
  assert.match(sql,/create unique index minds_chat_jobs_one_active_user_idx/);
  assert.match(sql,/where status in \('preparing','running'\)/);
  assert.match(sql,/alter table public\.minds_chat_jobs enable row level security/);
  assert.match(sql,/grant select on public\.minds_chat_jobs to authenticated/);
  assert.match(sql,/using\(user_id=auth\.uid\(\)\)/);
  assert.doesNotMatch(sql,/grant (?:insert|update|delete|all) on public\.minds_chat_jobs to authenticated/i);
  assert.ok(server.includes('client_message_id'));
  assert.ok(server.includes('existing)return json({durable:true'));
  assert.ok(server.includes('onConflict')===false||server.includes('minds_chat_jobs'));
  assert.ok(server.includes('status:"preparing"'));
  assert.ok(server.includes('provider_response_id:String(payload.id)'));
